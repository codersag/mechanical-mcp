"""Generators for the Workbench-embedded ACP route (no PyACP, no listener).

Workbench's own ACP speaks the legacy ``compolyx`` API. It is driven from a Workbench journal / script session with
``<ACP Setup container>.RunScript(ScriptPath=...)``. This module writes the script that runs *inside* ACP and the
Workbench-side commands that run it; both are plain text, so they can be unit-tested without ANSYS.

Lessons baked in (ACP 2026 R1):
* ACP materials come from the system's Engineering Data cell. ``material_data.create_material`` fails in Workbench
  ("Operation implies creating of materials not defined in current workbench project"), so import a composite material
  into Engineering Data first (e.g. ``ed.ImportMaterial(Name=..., Source="Composite_Materials.xml")``).
* Use ``model.material_data`` (not ``db.material_data``) for fabrics; plies need a fabric whose material has engineering
  constants, otherwise ``model.update()`` fails.
* A failed ``create_modeling_ply`` leaves a half-built ply (no material, no oriented selection set) which makes every later
  update fail; the script repairs existing plies before adding new ones.
* ``db.active_model.wbupdate()`` must be the last call; without it Workbench never sees the solid model.
* The ACP system must be updated (``system.Update(AllDependencies=True)``) before ``RunScript`` ("External sources ... out of date").
* Link to Mechanical with ``setup_component.TransferData(TargetComponent=model_component)`` (journal-recorded form).
  For Thermal-Electric the transferred solid is one plain SOLID225 body (one material, one ESYS) whose plies are identifiable by
  section number (section = 3 + ply index); split them with ply_split_snippet().
"""

from __future__ import annotations

from pathlib import Path

ACP_SCRIPT_TEMPLATE = r"""# generated by acp-mcp: runs inside Workbench's ACP via Setup.RunScript
import traceback
_LOG = open(r"__LOG__", "w")
def log(s):
    _LOG.write(str(s) + "\n")
    _LOG.flush()
CFG = __CFG_DICT__
try:
    m = db.active_model
    md = m.material_data
    es = [m.element_sets[CFG["element_set"]]]
    fabs = {}
    for fname, (mname, thk) in CFG["fabrics"].items():
        mat = md.materials[mname]
        if fname in md.fabrics.keys():
            fabs[fname] = md.fabrics[fname]
            fabs[fname].material = mat
            fabs[fname].thickness = thk
        else:
            fabs[fname] = md.create_fabric(name=fname, material=mat, thickness=thk)
    ros = m.rosettes[CFG["rosette"]]
    if CFG["oss"] in m.oriented_selection_sets.keys():
        oss = m.oriented_selection_sets[CFG["oss"]]
    else:
        oss = m.create_oriented_selection_set(
            name=CFG["oss"], orientation_point=tuple(CFG["orientation_point"]),
            orientation_direction=tuple(CFG["orientation_direction"]), element_sets=es, rosettes=[ros],
            rosette_selection_method="minimum_angle")
    if CFG["group"] in m.modeling_groups.keys():
        g = m.modeling_groups[CFG["group"]]
    else:
        g = m.create_modeling_group(name=CFG["group"])
    specs = CFG["plies"]                          # list of [angle, fabric, layers]
    existing = list(g.plies.values())
    for i, p in enumerate(existing):            # repair plies left over from failed attempts / re-runs
        if i < len(specs):
            ang, fname, nl = specs[i]
            p.ply_material = fabs[fname]
            p.oriented_selection_sets = (oss,)
            p.ply_angle = float(ang)
            p.number_of_layers = int(nl)
    for ang, fname, nl in specs[len(existing):]:
        g.create_modeling_ply(ply_material=fabs[fname], ply_angle=float(ang), number_of_layers=int(nl),
                              oriented_selection_sets=(oss,))
    log("plies: %s" % [(p.name, p.ply_angle) for p in g.plies.values()])
    m.update()
    if CFG["solid_model"] and CFG["solid_model"] not in m.solid_models.keys():
        m.create_solid_model(name=CFG["solid_model"], element_sets=es, ex_type=CFG["ex_type"])
    m.update()
    log("solid models: %s" % list(m.solid_models.keys()))
    m.wbupdate()
    log("wbupdate ok")
except Exception:
    log(traceback.format_exc())
_LOG.close()
"""


def build_acp_script(
    *,
    material: str | None = None,
    angles: list[float] | None = None,
    layers: int = 1,
    ply_thickness_m: float = 0.125e-3,
    fabric: str = "ply",
    group: str = "mg",
    oss: str = "oss",
    rosette: str = "Global Coordinate System",
    element_set: str = "All_Elements",
    orientation_point=(0.0, 0.0, -1.0),
    orientation_direction=(0.0, 0.0, 1.0),
    solid_model: str = "solid",
    ex_type: str = "analysis_ply_wise",
    log_path: str = r"C:\Temp\acp_build_log.txt",
    plies: list | None = None,
    fabrics: dict | None = None,
) -> str:
    """Return the legacy-API script that builds the layup inside Workbench's ACP and ends with ``wbupdate()``.

    Simple form: ``material`` + ``angles`` (+ ``layers``, ``ply_thickness_m``): one fabric, one ply per angle.
    General form: ``fabrics={name: (engineering_data_material, thickness_m)}`` and
    ``plies=[(angle_deg, fabric_name, number_of_layers), ...]`` in stacking order (first = against the reference surface).
    """
    if plies is None:
        if not angles or material is None:
            raise ValueError("angles and material are required (or pass plies and fabrics)")
        fabrics = {fabric: (material, float(ply_thickness_m))}
        plies = [(float(a), fabric, int(layers)) for a in angles]
    if not plies or not fabrics:
        raise ValueError("plies and fabrics must not be empty")
    for ang, fname, nl in plies:
        if fname not in fabrics:
            raise ValueError("ply references unknown fabric %r" % fname)
    cfg = {
        "fabrics": {k: [v[0], float(v[1])] for k, v in fabrics.items()},
        "plies": [[float(a), f, int(n)] for a, f, n in plies],
        "group": group,
        "oss": oss,
        "rosette": rosette,
        "element_set": element_set,
        "orientation_point": list(orientation_point),
        "orientation_direction": list(orientation_direction),
        "solid_model": solid_model,
        "ex_type": ex_type,
    }
    return ACP_SCRIPT_TEMPLATE.replace("__LOG__", log_path).replace("__CFG_DICT__", repr(cfg))


def workbench_commands(
    *,
    acp_system: str,
    acp_setup: str,
    script_path: str,
    mechanical_system: str | None = None,
    mechanical_model: str | None = None,
) -> str:
    """Workbench-side commands (run in a Workbench scripting session) that execute the ACP script and, optionally,
    link the ACP Setup cell to a Mechanical Model cell."""
    lines = [
        "a = [s for s in GetAllSystems() if s.Name == %r][0]" % acp_system,
        "a.Update(AllDependencies=True)          # ACP must be up to date before RunScript",
        'a.GetContainer(ComponentName=%r).RunScript(ScriptPath=r"%s")' % (acp_setup, script_path),
        "a.Update(AllDependencies=True)",
    ]
    if mechanical_system and mechanical_model:
        lines += [
            "mech = [s for s in GetAllSystems() if s.Name == %r][0]" % mechanical_system,
            "a.GetComponent(Name=%r).TransferData(TargetComponent=mech.GetComponent(Name=%r))"
            % (acp_setup, mechanical_model),
            "mech.Update(AllDependencies=True)",
        ]
    return "\n".join(lines)


def ply_split_snippet(
    angles: list[float | None],
    *,
    first_section: int = 3,
    source_mat: int = 1,
    first_new_mat: int = 11,
    first_csys: int = 21,
    tbdata: str = "1e6,8.33e11,1.8e5",
    tbdata2: str = "3.5,1,0,0.1",
) -> str:
    """Mechanical command snippet for a Thermal-Electric body transferred from ACP.

    For Thermal-Electric the transferred solid is plain SOLID225 with one material and one ESYS, but every ply keeps its own
    section number (first_section + ply index; verified: each section = one ply = 1/n of the elements). This snippet gives
    each ply its own material (copy of ``source_mat``), its own element coordinate system rotated by the ply angle, and the
    pyrolysis ``TB,USER`` data. ``None`` as an angle marks an isotropic (bulk) layer. Body-level snippet.
    """
    out = [
        "! split ACP plies by section number: own material, orientation and TB,USER per ply",
        "ALLSEL",
    ]
    for i, ang in enumerate(angles):
        sec, mat, cs = first_section + i, first_new_mat + i, first_csys + i
        iso = 1 if ang is None else 0
        a = 0.0 if ang is None else float(ang)
        out += [
            "LOCAL,%d,0,0,0,0,%g" % (cs, a),
            "CSYS,0",
            "ESEL,S,SECN,,%d" % sec,
            "MPCOPY,,%d,%d" % (source_mat, mat),
            "EMODIF,ALL,MAT,%d" % mat,
            "EMODIF,ALL,ESYS,%d" % cs,
            "TB,USER,%d,1,10,THERM" % mat,
            "TBTEMP,20",
            "TBDATA,1,%g,%d,1,%s" % (a, iso, tbdata),
            "TBDATA,7,%s" % tbdata2,
            "ALLSEL",
        ]
    return "\n".join(out) + "\n"


def _property_lines(mat: int, temps: list, props: dict) -> list[str]:
    """MPTEMP + MPDATA commands (6 values per command) defining ``mat`` from temperature tables."""
    out = ["MPTEMP"]
    for k in range(0, len(temps), 6):
        out.append("MPTEMP,%d,%s" % (k + 1, ",".join("%.9g" % t for t in temps[k : k + 6])))
    for name, vals in props.items():
        for k in range(0, len(vals), 6):
            out.append(
                "MPDATA,%s,%d,%d,%s"
                % (name, mat, k + 1, ",".join("%.9g" % v for v in vals[k : k + 6]))
            )
    return out


def ply_split_by_depth_snippet(
    layers: list,
    *,
    carbon_mat: int = 1,
    bulk_mat: int = 9,
    first_new_mat: int = 11,
    first_csys: int = 21,
    tbdata: str = "1e6,8.33e11,1.8e5",
    tbdata2: str = "3.5,1,0,0.1",
    bulk_props: dict | None = None,
    bulk_temps: list | None = None,
) -> str:
    """Body-level Mechanical snippet that splits an ACP-transferred Thermal-Electric solid into layers BY DEPTH.

    ``layers`` = [(angle_deg or None for isotropic bulk, thickness_m), ...] from the strike surface (z = 0) downward, in solver
    units of metres. Section numbers are not in stacking order after ACP edits, so layers are selected with
    ``ESEL,S,CENT,Z`` (both signs of z are tried). Each layer gets a material copy of ``carbon_mat`` (plies) or
    ``bulk_mat`` (None angle), its own ESYS rotated about global Z, and the pyrolysis ``TB,USER`` data.

    Only the body's material (``carbon_mat``, the ply material assigned to the body) is sent to the solver for a Thermal-Electric
    analysis, so a second material such as the bulk layer must be defined here: pass ``bulk_props`` ({MPDATA label: values at
    ``bulk_temps``}) and it is written as material ``bulk_mat`` before the layers are split.
    """
    out = [
        "! split ACP layers by depth: own material copy, orientation and TB,USER per layer",
        "ALLSEL",
    ]
    if bulk_props:
        out += ["! bulk-layer material (not transferred by the ACP link)"] + _property_lines(
            bulk_mat, bulk_temps or [], bulk_props
        )
    z = 0.0
    for i, (ang, thk) in enumerate(layers):
        mat, cs = first_new_mat + i, first_csys + i
        iso = 1 if ang is None else 0
        a = 0.0 if ang is None else float(ang)
        src = bulk_mat if ang is None else carbon_mat
        lo, hi = z, z + float(thk)
        z = hi
        out += [
            "LOCAL,%d,0,0,0,0,%g" % (cs, a),
            "CSYS,0",
            "ESEL,S,CENT,Z,%.9g,%.9g" % (lo, hi),
            "ESEL,A,CENT,Z,%.9g,%.9g" % (-hi, -lo),
            "MPCOPY,,%d,%d" % (src, mat),
            "EMODIF,ALL,MAT,%d" % mat,
            "EMODIF,ALL,ESYS,%d" % cs,
            "TB,USER,%d,1,10,THERM" % mat,
            "TBTEMP,20",
            "TBDATA,1,%g,%d,1,%s" % (a, iso, tbdata),
            "TBDATA,7,%s" % tbdata2,
            "ALLSEL",
        ]
    return "\n".join(out) + "\n"


def write_build_script(path: str | Path, **kw) -> str:
    p = Path(path)
    p.write_text(build_acp_script(**kw), encoding="utf-8")
    return str(p)


