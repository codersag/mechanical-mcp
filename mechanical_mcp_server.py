_XML_BAD = re.compile("[\x00-\x08\x0b\x0c\x0e-\x1f\ufffe\uffff\ud800-\udfff]")


def _bc_line(bc) -> str:
    """One boundary condition: name (type), scope and key values."""
    if not isinstance(bc, dict):
        return str(bc)
    parts = [str(bc.get("name", "")) + " (" + str(bc.get("type", "")) + ")"]
    scope = bc.get("scope_named_selection")
    n = bc.get("scope_entities")
    if scope or n is not None:
        parts.append(
            "scope: "
            + (str(scope) if scope else "geometry selection")
            + (" [%s entities]" % n if n is not None else "")
        )
    vals = bc.get("values") or {}
    if vals:
        parts.append(", ".join("%s=%s" % (k, v) for k, v in vals.items()))
    if bc.get("suppressed"):
        parts.append("SUPPRESSED")
    return " | ".join(parts)


def _clean_text(s) -> str:
    """Text that python-docx can write: XML 1.0 does not allow control characters."""
    return _XML_BAD.sub("?", str(s))


def _publish(tmp: Path, dest: Path, overwrite: bool) -> None:
    """Move tmp to dest. Without overwrite an existing dest is an error (hard link, not rename,
    so it cannot replace a file created in the meantime)."""
    if overwrite:
        os.replace(tmp, dest)
        return
    try:
        os.link(tmp, dest)
    except FileExistsError:
        raise
    except OSError:
        if dest.exists():
            raise FileExistsError(str(dest)) from None
        os.rename(
            tmp, dest
        )  # no hard links on this file system; rename refuses to replace on Windows
        return
    tmp.unlink()


def _write_docx(path: Path, data: dict, now: str) -> None:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    c = _clean_text
    doc = Document()
    t = doc.add_heading("ANSYS Mechanical Simulation Report", 0)
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph("Generated: " + now)
    doc.add_paragraph(
        "Analysis: "
        + c(data.get("analysis_name", "N/A"))
        + " ("
        + c(data.get("analysis_type", "N/A"))
        + ")"
    )
    doc.add_paragraph("Status: " + c(data.get("solution_status", "N/A")))
    doc.add_heading("1. Geometry", level=1)
    tbl = doc.add_table(rows=1, cols=2)
    tbl.style = "Table Grid"
    tbl.rows[0].cells[0].text = "Body"
    tbl.rows[0].cells[1].text = "Material"
    for b in data.get("bodies", []):
        row = tbl.add_row().cells
        row[0].text = c(b.get("name", ""))
        row[1].text = c(b.get("material", "N/A"))
    doc.add_heading("2. Mesh", level=1)
    doc.add_paragraph("Nodes: " + c(data.get("nodes", "N/A")))
    doc.add_paragraph("Elements: " + c(data.get("elements", "N/A")))
    doc.add_heading("3. Boundary Conditions", level=1)
    for bc in data.get("boundary_conditions", []):
        doc.add_paragraph(c(_bc_line(bc)), style="List Bullet")
    doc.add_heading("4. Results", level=1)
    tbl2 = doc.add_table(rows=1, cols=4)
    tbl2.style = "Table Grid"
    for i, h in enumerate(("Result", "Mode", "Frequency (Hz)", "Max Value")):
        tbl2.rows[0].cells[i].text = h
    for r in data.get("results", []):
        row = tbl2.add_row().cells
        row[0].text = c(r.get("name", ""))
        row[1].text = c(r.get("mode", "-"))
        row[2].text = c(r.get("freq", "-"))
        row[3].text = c(r.get("max", "-"))
    doc.save(str(path))


def _txt_report(data: dict, now: str) -> str:
    g = lambda d, k, default="": str(d.get(k, default))  # noqa: E731
    lines = [
        "ANSYS MECHANICAL SIMULATION REPORT",
        "Generated: " + now,
        "Analysis: " + g(data, "analysis_name") + " (" + g(data, "analysis_type") + ")",
        "Status: " + g(data, "solution_status"),
        "",
        "GEOMETRY",
    ]
    for b in data.get("bodies", []):
        lines.append("  " + g(b, "name") + " | " + g(b, "material", "N/A"))
    lines += [
        "",
        "MESH",
        "  Nodes: " + g(data, "nodes"),
        "  Elements: " + g(data, "elements"),
        "",
        "BOUNDARY CONDITIONS",
    ]
    for bc in data.get("boundary_conditions", []):
        lines.append("  " + _bc_line(bc))
    lines += ["", "RESULTS"]
    for r in data.get("results", []):
        lines.append(
            "  "
            + g(r, "name")
            + " | Mode: "
            + g(r, "mode", "-")
            + " | Freq: "
            + g(r, "freq", "-")
            + " | Max: "
            + g(r, "max", "-")
        )
    return _clean_text("\n".join(lines))


@_tool
def generate_report(
    output_path: str, analysis_index: int = 0, fmt: str = "docx", overwrite: bool = False
) -> str:
    """Generate a simulation report (docx needs python-docx: pip install ansys-mechanical-mcp[report]).
    output_path must be inside MECHANICAL_MCP_ROOTS (default: the server's working directory),
    end in .docx or .txt matching fmt, and not exist unless overwrite=true.
    Args: output_path, analysis_index, fmt (docx or txt), overwrite"""
    idx = ms.index(analysis_index)
    f = fmt.strip().lower() if isinstance(fmt, str) else ""
    if f not in ("docx", "txt"):
        raise ValueError("fmt must be 'docx' or 'txt' (pdf is not supported)")
    p, err = _allow(output_path, exts={"." + f}, write=True, overwrite=bool(overwrite))
    if err:
        return err
    if f == "docx":
        try:
            import docx  # noqa: F401
        except ImportError:
            return _json(
                {
                    "ok": False,
                    "error": "python-docx is not installed: pip install ansys-mechanical-mcp[report]",
                }
            )
    script = _REPORT_SCRIPT.replace("{pick}", ms.pick_analysis(idx)).replace(
        "{loads}", ms.LOADS_DEFS
    )
    err = _check_connection()
    if err:
        return err
    raw = _run(script)
    serr = _script_error(raw)
    if serr is not None:
        return _json({"ok": False, "error": serr})
    data = _extract_json(raw)
    if data is None:
        return _json({"ok": False, "error": "Failed to gather report data: " + raw[:300]})
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    tmp = None
    try:
        # a uniquely named, exclusively created file in the same folder: a pre-existing unrelated
        # file is never touched, and the temporary is the only thing removed on failure
        handle, tmp_name = tempfile.mkstemp(prefix=p.name + ".", suffix=".part", dir=str(p.parent))
        os.close(handle)
        tmp = Path(tmp_name)
        if f == "docx":
            _write_docx(tmp, data, now)
        else:
            tmp.write_text(_txt_report(data, now), encoding="utf-8")
        _publish(tmp, p, overwrite=bool(overwrite))
        tmp = None
    except Exception as e:
        if tmp is not None:
            try:
                tmp.unlink()
            except OSError:
                pass
        return _json({"ok": False, "error": "Could not write the report: %s" % e})
    return _json({"ok": True, "report_path": str(p), "format": f})


