# The port survives a server restart here. It lives in a per-user folder, not the shared system
# temp folder: another user or program must not be able to point this server at a port of its
# choosing.
_STATE_FILE = _state_dir() / "mechanical_port.json"

#: One lock for the Mechanical connection: opening, dropping and using it. Re-entrant because _run
#: holds it while it drops a broken channel. Tools run on worker threads (see _tool) and two
#: scripts interleaving on one Mechanical session would corrupt each other's state.
_MECH_LOCK = threading.RLock()
LOCK_WAIT_S = float(os.environ.get("MECHANICAL_MCP_LOCK_WAIT_S", "60"))

_POOL = ThreadPoolExecutor(max_workers=8, thread_name_prefix="mech-tool")
#: Status and control tools have their own workers, so a flood of waiting Mechanical calls can
#: never starve the "busy" answer they exist to give.
_FAST_POOL = ThreadPoolExecutor(max_workers=4, thread_name_prefix="mech-fast")
_FAST_TOOLS = frozenset(
    {"check_mechanical_connection", "get_solve_status", "disconnect_from_mechanical"}
)
#: At most this many calls queue for the Mechanical lock; the next one is told "busy" at once
#: instead of pinning a worker for LOCK_WAIT_S.
MAX_WAITERS = int(os.environ.get("MECHANICAL_MCP_MAX_WAITERS", "4"))
_WAIT_LOCK = threading.Lock()
_WAITERS = 0


def _acquire_mech(timeout):
    """Take the Mechanical lock, waiting up to `timeout` unless MAX_WAITERS calls already wait."""
    global _WAITERS
    if _MECH_LOCK.acquire(blocking=False):
        return True
    with _WAIT_LOCK:
        if _WAITERS >= MAX_WAITERS:
            return False
        _WAITERS += 1
    try:
        return _MECH_LOCK.acquire(timeout=timeout)
    finally:
        with _WAIT_LOCK:
            _WAITERS -= 1


def _tool(fn):
    """Register fn as an MCP tool that runs on a worker thread.

    FastMCP runs a plain function directly on the event loop, so one slow call (a long solve)
    froze every other tool. ValueError from argument validation becomes an ok:false response, and
    every tool reports a silent re-attachment (reconnected_to) exactly once. The module-level name
    stays a plain (guarded) function so tests can call it directly.
    """

    @functools.wraps(fn)
    def guarded(*args, **kwargs):
        try:
            out = fn(*args, **kwargs)
        except ValueError as e:
            out = _json({"ok": False, "error": str(e)})
        return paths.redact(_with_reconnect_note(out)) if isinstance(out, str) else out

    @functools.wraps(fn)
    async def runner(*args, **kwargs):
        pool = _FAST_POOL if fn.__name__ in _FAST_TOOLS else _POOL
        return await asyncio.get_running_loop().run_in_executor(
            pool, functools.partial(guarded, *args, **kwargs)
        )

    mcp.tool(name=fn.__name__, description=fn.__doc__)(runner)
    return guarded


def _clean(o):
    """Make NaN/Infinity JSON-safe: they are not valid JSON."""
    if isinstance(o, float) and not math.isfinite(o):
        return "NaN" if math.isnan(o) else ("Infinity" if o > 0 else "-Infinity")
    if isinstance(o, dict):
        return {k: _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    return o


def _json(data):
    return json.dumps(_clean(data), indent=2, ensure_ascii=False)


