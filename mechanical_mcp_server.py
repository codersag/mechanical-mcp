class ProjectMismatch(ConnectionError):
    pass


class HandshakeTimeout(ConnectionError):
    """Mechanical did not answer in time (a busy GUI, or not Mechanical at all): not a refusal."""


class BusyError(ConnectionError):
    pass


#: Handshakes still waiting in a thread (a socket that never answers pins its thread until the
#: OS gives up); a few at a time is the cap, then new attempts are refused.
_HANDSHAKES = threading.BoundedSemaphore(2)


_LIN_SLOT = threading.BoundedSemaphore(1)


def _call_with_timeout(
    fn, seconds, on_late=None, limiter=None, limiter_message=None, on_timeout=None
):
    """Run fn() on a daemon thread; raise TimeoutError after `seconds`.

    The result is either returned or, if it arrives after the timeout, passed to on_late as a
    one-item list so it can be dropped properly: a lock decides, atomically, which of the two
    happens, so a result landing exactly at the deadline is never lost. A limiter (semaphore)
    bounds the number of threads that may be stuck at once.
    """
    if limiter is not None and not limiter.acquire(blocking=False):
        raise BusyError(
            limiter_message or "too many connection attempts are still waiting for an answer"
        )
    box: dict = {}
    done = threading.Event()
    lk = threading.Lock()
    state = {"finished": False, "abandoned": False}

    def run():
        try:
            box["v"] = fn()
        except Exception as e:  # noqa: BLE001 - re-raised in the caller
            e.__cause__ = None
            e.__context__ = None
            box["exc"] = e.with_traceback(None)
        finally:
            if limiter is not None:
                limiter.release()
        with lk:
            state["finished"] = True
            late = state["abandoned"]
        done.set()
        if late and "v" in box and on_late is not None:
            on_late([box.pop("v")])

    threading.Thread(target=run, daemon=True, name="mech-timeout-call").start()
    if not done.wait(seconds):
        with lk:
            if not state["finished"]:
                state["abandoned"] = True
                if on_timeout is not None:
                    on_timeout()
                raise TimeoutError("no answer within %g s" % seconds)
        done.wait()  # it finished at the boundary: take the result normally
    if "exc" in box:
        raise box.pop("exc")
    return box.pop("v")


def _connect_impl(port: int, expect_project: str = "") -> dict:
    """Open a connection, check it answers, and only then replace the current one.

    Neither the Mechanical lock nor any other lock is held while waiting for the handshake. The
    handshake and the first script are bounded by CONNECT_TIMEOUT_S, and only a few may be pending
    at once. Returns the analyses listing; raises on any failure, leaving the current connection
    (if any) untouched.
    """
    global _mechanical, _port
    import ansys.mechanical.core as mech

    if not _port_open(port):
        raise ConnectionError(
            "Nothing is listening on localhost:%d. Is Mechanical running with that port?" % port
        )
    if _silent(port):
        raise HandshakeTimeout(
            "localhost:%d accepts connections but does not speak gRPC (it never answered the "
            "handshake): that is not a Mechanical session" % port
        )
    try:
        conn = _call_with_timeout(
            lambda: mech.connect_to_mechanical(port=port, connect_timeout=CONNECT_TIMEOUT_S),
            CONNECT_TIMEOUT_S,
            on_late=_drop,
            limiter=_HANDSHAKES,
        )
    except TimeoutError:
        raise HandshakeTimeout(
            "localhost:%d accepted the connection but Mechanical did not answer within %g s "
            "(is that port really a Mechanical session?)" % (port, CONNECT_TIMEOUT_S)
        ) from None
    holder = [conn]
    del conn
    failed = None
    stuck = False
    data = None
    try:
        raw = _call_with_timeout(
            lambda: _execute(holder[0], _INFO_SCRIPT, True),
            CONNECT_TIMEOUT_S,
            limiter=_HANDSHAKES,
        )
        err = _script_error(raw)
        data = _extract_json(raw)
        if err is not None or data is None:
            failed = err or "Mechanical did not answer the connection check: %s" % raw[:300]
    except (TimeoutError, BusyError):
        failed = "Mechanical did not run the connection check within %g s" % CONNECT_TIMEOUT_S
        stuck = True
    except Exception as e:  # noqa: BLE001
        failed = str(e) or type(e).__name__
    # out of the except block before dropping (see _drop)
    ident = paths.project_identity(data.get("project") if data else "")
    if failed is None and expect_project and ident["id"] != expect_project:
        failed = "mismatch"
    if failed is not None:
        _drop(holder, close=not stuck)
        if failed == "mismatch":
            raise ProjectMismatch(
                "port %d now serves a different project (%s) than the one this server was "
                "connected to; call connect_to_mechanical to attach to it deliberately"
                % (port, ident["name"] or "unsaved")
            )
        if stuck:
            raise HandshakeTimeout(failed)
        raise ConnectionError(failed)
    if not _acquire_mech(LOCK_WAIT_S):
        _drop(holder)
        raise BusyError("Mechanical is busy with another call; try again shortly")
    try:
        old = [_mechanical]
        _mechanical, _port = holder.pop(), port
        _drop(old)
        _remember_port(port, ident)
        _CONN_INFO["analyses"] = len(data.get("analyses", []))
    finally:
        _MECH_LOCK.release()
    return {
        "analyses": data.get("analyses", []),
        "project": ident["name"],
        "project_id": ident["id"],
    }


def _connect(port: int, expect_project: str = "") -> dict:
    if not _CONNECT_LOCK.acquire(timeout=LOCK_WAIT_S):
        raise BusyError("another connection attempt is in progress")
    try:
        return _connect_impl(port, expect_project)
    finally:
        _CONNECT_LOCK.release()


def _busy() -> str:
    return _json(
        {
            "ok": False,
            "busy": True,
            "connected": _mechanical is not None,
            "error": "Mechanical is busy with another call (for example a solve). Try again shortly.",
        }
    )


class _Locked:
    """Context manager for the Mechanical lock; `.ok` says whether it was taken.

    With an explicit `wait` (status probes) it waits that long and never queues behind the cap.
    Without one it waits up to LOCK_WAIT_S, but is refused at once when MAX_WAITERS calls are
    already waiting."""

    def __init__(self, wait=None):
        self.wait = wait

    def __enter__(self):
        if self.wait is None:
            self.ok = _acquire_mech(LOCK_WAIT_S)
        else:
            self.ok = _MECH_LOCK.acquire(timeout=self.wait)
        return self

    def __exit__(self, *exc):
        if self.ok:
            _MECH_LOCK.release()


def _not_connected() -> str:
    return _json(
        {"ok": False, "error": "Not connected to Mechanical. Call connect_to_mechanical first."}
    )


def _check_connection():
    """Return an error payload if unusable, else None.

    With no connection, one reconnect to the remembered port is tried -- only if a project
    identity was stored with it and the port still serves that project (an empty identity, e.g. an
    unsaved project, could be anything). The remembered port is forgotten when the port refuses
    connections or the project changed, or after MAX_RECONNECT_FAILS bad answers in a row; busy
    sessions and timeouts are not refusals and never count.
    """
    global _RECONNECT_FAILS
    # the background solve thread itself must get through, everyone else is told Mechanical is busy
    if _background_running() and threading.current_thread() is not _BG["thread"]:
        return _busy()
    if _mechanical is not None:
        return None
    st = _last_state()
    if not st:
        return _not_connected()
    if not st.get("project"):
        return _json(
            {
                "ok": False,
                "error": "Not connected to Mechanical. The remembered session (port %d) has no project "
                "identity, so it is not re-attached silently; call connect_to_mechanical."
                % st["port"],
            }
        )
    if not _CONNECT_LOCK.acquire(blocking=False):
        return _busy()
    failure = None
    try:
        if _mechanical is not None:
            return None
        try:
            data = _connect_impl(st["port"], st["project"])
        except ProjectMismatch as e:
            _forget_port()
            return _json({"ok": False, "error": str(e)})
        except (HandshakeTimeout, BusyError) as e:
            failure = str(e)  # busy, not refused: keep the port, do not count
        except ConnectionError as e:
            failure = str(e)
            if not _port_open(st["port"]):
                _forget_port()  # the session is gone
                _RECONNECT_FAILS = 0
            else:
                _RECONNECT_FAILS += 1
                if _RECONNECT_FAILS >= MAX_RECONNECT_FAILS:
                    _forget_port()
                    _RECONNECT_FAILS = 0
        except Exception as e:  # noqa: BLE001
            failure = str(e)
            _RECONNECT_FAILS += 1
            if _RECONNECT_FAILS >= MAX_RECONNECT_FAILS:
                _forget_port()
                _RECONNECT_FAILS = 0
        else:
            _RECONNECT_FAILS = 0
            _RECONNECTED.clear()
            _RECONNECTED.update({"port": st["port"], "project": data.get("project", "")})
            return None
    finally:
        _CONNECT_LOCK.release()
    return _json(
        {
            "ok": False,
            "error": "Not connected to Mechanical (reconnecting to the remembered port %d failed: %s). "
            "Call connect_to_mechanical." % (st["port"], failure),
        }
    )


