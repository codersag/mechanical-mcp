_BG: dict = {
    "thread": None,
    "result": None,
    "started": 0.0,
    "finished": 0.0,
    "analysis": 0,
    "history": [],
}
#: Set when a Solve request did not come back (timeout, dropped channel): Mechanical may still be
#: solving, and sending another Solve then could start a second one.
_SOLVE_UNKNOWN: dict = {}
HISTORY_MAX = 5
#: Serialises starting a background solve; a second start is refused at once instead of waiting
#: for the Mechanical lock (which the first solve holds for its whole duration).
_BG_START = threading.Lock()
#: An unread background result is dropped after this long.
BG_RESULT_TTL_S = 3600.0


def _background_running() -> bool:
    t = _BG["thread"]
    return t is not None and t.is_alive()


def _solve_script(idx: int) -> str:
    # Solve(True) always: Mechanical's local solve configuration refuses wait=False. A solve
    # that must not block the caller is run on a background thread instead (see
    # _start_background_solve). The Messages pane is NOT cleared -- it is the user's; messages
    # added by this solve are the ones after the count taken before it.
    return (
        "import json\n" + ms.pick_analysis(idx) + _MESSAGES + "try:\n"
        "    _skip = len(ExtAPI.Application.Messages)\n"
        "except Exception:\n"
        "    _skip = 0\n"
        "_err = None\n"
        "try:\n"
        "    _analysis.Solution.Solve(True)\n"
        "except Exception as _e:\n"
        "    _err = str(_e)\n"
        "_msgs = _collect_msgs(_skip)\n"
        "_status = str(_analysis.Solution.Status)\n"
        "_errs = [m for m in _msgs if m.startswith('Error')]\n"
        "_ok = (_err is None) and (_status == 'Done')\n"
        "print(json.dumps({'ok': _ok, 'status': _status, 'solved': _status == 'Done', 'error': _err, "
        "'error_messages': _errs, 'messages': _msgs, 'waited': True}))\n"
    )


def _solve_guard(confirm: bool):
    u = _SOLVE_UNKNOWN
    if u and not confirm:
        return _json(
            {
                "ok": False,
                "error": "The previous solve request (analysis %s) did not come back (%s), so Mechanical may "
                "still be solving it; a second Solve could start another. Check get_solve_status or "
                "the Mechanical window, then pass confirm_not_running=true to solve again."
                % (u.get("analysis"), u.get("why")),
            }
        )
    return None


def _track_solve(idx: int, result: str) -> str:
    try:
        doc = json.loads(result)
    except ValueError:
        return result
    if "connection dropped" in str(doc.get("error", "")):
        _SOLVE_UNKNOWN.clear()
        _SOLVE_UNKNOWN.update({"analysis": idx, "why": "connection dropped", "at": time.time()})
    else:
        _SOLVE_UNKNOWN.clear()
    return result


def _solve_sync(idx: int, confirm: bool = False) -> str:
    refused = _solve_guard(confirm)
    if refused:
        return refused
    return _track_solve(idx, _scripted(_solve_script, idx))


def _start_background_solve(idx: int, confirm: bool = False) -> str:
    if not _BG_START.acquire(blocking=False):
        return _json({"ok": False, "error": "A solve is already being started"})
    try:
        if _background_running():
            return _json(
                {
                    "ok": False,
                    "error": "A solve started by this server is still running (status: Solving)",
                }
            )
        refused = _solve_guard(confirm)
        if refused:
            return refused
        err = _check_connection()
        if err:
            return err
        if _BG["result"]:  # keep the last result until it is read: it moves to the history
            _BG.setdefault("history", []).append(
                {"analysis": _BG["analysis"], "finished": _BG["finished"], "text": _BG["result"]}
            )
            del _BG["history"][:-HISTORY_MAX]
        _BG.update(result=None, started=time.time(), finished=0.0, analysis=idx)

        def run():
            try:
                _BG["result"] = _solve_sync(idx, True)
            except Exception as e:  # noqa: BLE001 - reported through get_solve_status
                _BG["result"] = _json({"ok": False, "error": "solve failed: %s" % e})
            _BG["finished"] = time.time()

        _BG["thread"] = threading.Thread(target=run, daemon=True, name="mechanical-solve")
        _BG["thread"].start()
    finally:
        _BG_START.release()
    return _json(
        {
            "ok": True,
            "started": True,
            "status": "Solving",
            "analysis": idx,
            "note": "Solving in the background; other Mechanical tools report busy until it ends. "
            "Poll get_solve_status.",
        }
    )


@_tool
def solve_analysis(
    analysis_index: int | None = None,
    wait: bool = True,
    confirm_not_running: bool = False,
    analysis_name: str = "",
    expect_analysis_type: str = "",
) -> str:
    """Solve the analysis. Progress visible in GUI. Returns solver messages. ok:true only if the
    status is Done. Mechanical's Messages pane is not cleared. If a previous solve request did not
    come back (client timeout, dropped channel) a new one is refused until you check that nothing
    is still running and pass confirm_not_running=true.
    Args: analysis_index, wait (False starts the solve on a background thread and returns at
    once - then poll get_solve_status; use it for solves longer than the client call timeout),
    confirm_not_running
    analysis_name / expect_analysis_type: choose the analysis by name, or refuse unless it is of this
    type (e.g. "Static"). With several analyses in the model, analysis_index or analysis_name must be
    given explicitly; every reply names the analysis it used ("analysis")."""
    idx = ms.index(analysis_index, name=analysis_name, expect=expect_analysis_type, mutating=True)
    if not isinstance(wait, bool) or not isinstance(confirm_not_running, bool):
        raise ValueError("wait and confirm_not_running must be true or false")
    if wait:
        return _solve_sync(idx, confirm_not_running)
    if analysis_name or expect_analysis_type:
        raise ValueError(
            "wait=false needs analysis_index (analysis_name / expect_analysis_type apply to blocking solves)"
        )
    if not idx.explicit and os.environ.get("MECHANICAL_MCP_REQUIRE_EXPLICIT_ANALYSIS", "1") != "0":
        pass  # the blocking path checks this inside Mechanical; the background start checks below
    return _start_background_solve(int(idx), confirm_not_running)


@_tool
def get_solve_status(analysis_index: int = 0) -> str:
    """Get solve status. While a solve started with wait=False is running this answers
    'Solving' (naming the analysis) without touching Mechanical; for another analysis it says
    which one is solving. While another call holds Mechanical (a blocking solve) it answers busy
    at once. A finished background solve's result is kept until it is read: it is attached to the
    poll for the SAME analysis that really reached Mechanical (older unread ones for that
    analysis come as earlier_unread_solves) and expires after an hour. The messages are
    Mechanical's global Messages pane, not specific to this analysis.
    Args: analysis_index"""
    idx = ms.index(analysis_index)
    if _background_running():
        n = _BG["analysis"]
        known = _CONN_INFO.get("analyses")
        if known is not None and idx >= max(known, n + 1):
            return _json(
                {
                    "ok": False,
                    "error": "analysis_index %d is out of range: the model has %d analyses"
                    % (idx, known),
                }
            )
        if idx == n:
            return _json(
                {
                    "ok": True,
                    "status": "Solving",
                    "analysis": n,
                    "solved": False,
                    "in_background": True,
                    "seconds": round(time.time() - _BG["started"]),
                }
            )
        return _json(
            {
                "ok": True,
                "status": "Busy",
                "busy": True,
                "solving_analysis": n,
                "solved": False,
                "note": "analysis %d is being solved in the background; Mechanical cannot be asked about "
                "analysis %d until it ends" % (n, idx),
            }
        )
    script = (
        "import json\n"
        + ms.pick_analysis(idx)
        + _MESSAGES
        + "_status = str(_analysis.Solution.Status)\n"
        "_all_msgs = _collect_msgs(0)\n"
        "print(json.dumps({'ok': True, 'status': _status, 'solved': _status == 'Done', "
        "'solve_required': _status != 'Done', 'name': str(_analysis.Name), "
        "'type': str(_analysis.AnalysisType), 'messages': _all_msgs[-30:], "
        "'messages_total': len(_all_msgs), 'messages_scope': 'global Messages pane (all analyses)'}))\n"
    )
    err = _check_connection()
    if err:
        return err  # the unread background results stay for the next poll
    with _Locked(PROBE_WAIT_S) as lock:
        if not lock.ok:
            return _json(
                {
                    "ok": True,
                    "status": "Busy",
                    "busy": True,
                    "solved": False,
                    "note": "Mechanical is busy with another call (probably a blocking solve)",
                }
            )
        raw = _run(script)
    result = _with_reconnect_note(_result(raw))
    try:
        doc = json.loads(result)
    except ValueError:
        return result
    if not doc.get("ok"):
        return result
    if doc.get("status") == "Done":
        _SOLVE_UNKNOWN.clear()
    now = time.time()
    mine = []  # (finished, text), newest last
    for h in _BG.get("history", []):
        if h["analysis"] == idx and now - (h["finished"] or now) < BG_RESULT_TTL_S:
            mine.append((h["finished"], h["text"]))
    cur = _BG["result"]
    cur_mine = bool(
        cur
        and _BG["analysis"] == idx
        and now - (_BG.get("finished") or _BG.get("started") or now) < BG_RESULT_TTL_S
    )
    if cur_mine:
        mine.append((_BG["finished"], cur))
    if not mine:
        return result
    mine.sort(key=lambda t: t[0])
    try:
        docs = [json.loads(t) for _, t in mine]
    except ValueError:
        return result
    doc["last_solve"] = docs[-1]
    if len(docs) > 1:
        doc["earlier_unread_solves"] = docs[:-1]
    # consumed only now that the status call really reached Mechanical
    _BG["history"] = [h for h in _BG.get("history", []) if h["analysis"] != idx]
    if cur_mine:
        _BG["result"] = None
    return _json(doc)


