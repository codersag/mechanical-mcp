_SCRIPT_ERROR = "Script error:"
_RUN_ERROR = "Error: "


def _script_error(raw: str):
    """Return the failure text in raw _run output, or None if it succeeded."""
    for line in raw.split(chr(10)):
        stripped = line.strip()
        if stripped.startswith(_SCRIPT_ERROR):
            return stripped[len(_SCRIPT_ERROR) :].strip()
    if raw.startswith(_RUN_ERROR):
        return raw[len(_RUN_ERROR) :].strip()
    return None


def _extract_json(raw: str):
    """Pull the first JSON object out of raw output, past any ACT log lines."""
    for line in raw.split(chr(10)):  # not splitlines(): U+2028 inside a name must not split it
        line = line.strip()
        if line.startswith("{"):
            try:
                return json.loads(line)
            except Exception:
                pass
    return None


def _result(raw: str, key: str = ""):
    """Turn raw IronPython output into a tool response.

    A script that raised comes back as ok:false carrying the message; output that is not the
    expected JSON is an error too, never a success. A transport failure's raw text goes to
    `detail`, the error itself is one line; "busy" answers carry busy: true.
    """
    analysis = None
    for line in raw.split(chr(10)):
        if line.startswith("@@ANALYSIS "):
            try:
                analysis = json.loads(line[len("@@ANALYSIS ") :])
            except ValueError:
                pass
            break
    err = _script_error(raw)
    if err is not None:
        if err.startswith("Mechanical is busy"):
            return _busy()
        head, _, detail = err.partition("\n[detail] ")
        out = {"ok": False, "error": head}
        if detail:
            out["detail"] = detail[:1500]
        if analysis:
            out["analysis"] = analysis
        return _json(out)
    data = _extract_json(raw)
    if data is None:
        return _json({"ok": False, "error": "Unexpected output from Mechanical: " + raw[:500]})
    if analysis and isinstance(data, dict) and "analysis" not in data:
        data = {**data, "analysis": analysis}
    if key:
        return _json({"ok": True, key: data})
    if "ok" in data:
        return _json(data)
    return _json({"ok": True, **data})


def _checked_run(script, safe_text=True):
    """(error JSON, None) or (None, raw output). The connection check and the run are retried
    once if the connection disappeared between them."""
    for attempt in range(2):
        err = _check_connection()
        if err:
            return err, None
        raw = _run(script, safe_text)
        if raw.startswith("Error: not connected") and attempt == 0:
            continue
        return None, raw
    return _not_connected(), None  # pragma: no cover


def _with_reconnect_note(result: str) -> str:
    """Tell the caller when this call silently re-attached to the remembered session."""
    if not _RECONNECTED:
        return result
    note = dict(_RECONNECTED)
    _RECONNECTED.clear()
    try:
        doc = json.loads(result)
        doc["reconnected_to"] = note
        return _json(doc)
    except ValueError:
        return result


def _scripted(builder, *args, **kwargs) -> str:
    """Build the script (bad arguments become ok:false), check the connection, run it."""
    script = builder(*args, **kwargs)
    err, raw = _checked_run(script)
    if err:
        return err
    return _with_reconnect_note(_result(raw))


