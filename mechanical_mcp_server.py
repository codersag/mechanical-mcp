def _remember_port(port: int, project="") -> None:
    """Remember the port and WHICH project it served -- a hash of the project folder and the
    folder name, never the path (it contains the user name). `project` is a raw path or an
    identity dict from mcp_paths.project_identity."""
    ident = project if isinstance(project, dict) else paths.project_identity(project)
    try:
        _STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
        _STATE_FILE.write_text(
            json.dumps({"port": port, "project": ident["id"], "project_name": ident["name"]}),
            encoding="utf-8",
        )
    except Exception:
        pass


def _forget_port() -> None:
    try:
        _STATE_FILE.unlink()
    except Exception:
        pass


def _last_state() -> dict:
    try:
        st = json.loads(_STATE_FILE.read_text(encoding="utf-8"))
        port = int(st.get("port", 0))
    except Exception:
        return {}
    if not 1 <= port <= 65535:
        return {}
    return {
        "port": port,
        "project": str(st.get("project", "")),
        "name": str(st.get("project_name", "")),
    }


def _last_port() -> int:
    return _last_state().get("port", 0)


def _drop(holder: list, close: bool = True) -> None:
    """Drop the connection object held in holder (a one-item list), leaving Mechanical running.

    Order matters (found live: it crashed the whole server process with an access violation):
    PyMechanical's finalizer reads the channel's target, so the object must be finalized while
    the channel is still open, and only then is the channel closed. The finalizer's own
    'exit Mechanical on cleanup' flag is disarmed first, so dropping the object can never close
    the user's Mechanical session.

    The caller must hold no other reference to the object, and must NOT call this from inside an
    `except` block: the active traceback keeps the failing frames (and the object they
    reference) alive, so the finalizer would not run before the channel is closed. Record the
    failure, leave the block, then drop. close=False leaves the channel to the finalizer (used
    when a stuck thread still holds the object).
    """
    mech = holder.pop() if holder else None
    if mech is None:
        return
    channel = getattr(mech, "_channel", None)
    try:
        mech._cleanup_on_exit = False
    except Exception:
        pass
    del mech
    gc.collect()  # run the finalizer now, while the channel is still open
    if close and channel is not None:
        try:
            channel.close()
        except Exception:
            pass


def _close_channel() -> None:
    """Drop our connection without shutting Mechanical down."""
    global _mechanical, _port
    with _MECH_LOCK:
        holder = [_mechanical]
        _mechanical, _port = None, 0
        _drop(holder)


def _port_open(port: int) -> bool:
    """Is anything listening on localhost:port? A dead port would otherwise stall the gRPC client
    (and every tool queued behind the connection lock) for a minute or more."""
    import socket

    try:
        with socket.create_connection(("127.0.0.1", port), timeout=1.5):
            return True
    except OSError:
        return False


#: HTTP/2 client preface followed by an empty SETTINGS frame: a gRPC server answers with its own
#: SETTINGS within milliseconds; a plain listening socket that is not a gRPC server never does.
_H2_HELLO = b"PRI * HTTP/2.0\r\n\r\nSM\r\n\r\n" + bytes([0, 0, 0, 4, 0, 0, 0, 0, 0])


def _silent(port: int, wait: float = 2.0) -> bool:
    """True if something accepts connections on localhost:port but says nothing at all (neither a
    reply nor a close). pymechanical would wait up to its own long timeout on such a socket; one
    probe of a couple of seconds spares every connection attempt that."""
    import socket

    try:
        with socket.create_connection(("127.0.0.1", port), timeout=1.5) as sock:
            sock.sendall(_H2_HELLO)
            sock.settimeout(wait)
            try:
                sock.recv(1)  # data, or b"" when the peer closed: either way it is alive
                return False
            except socket.timeout:
                return True
            except OSError:
                return False
    except OSError:
        return False


