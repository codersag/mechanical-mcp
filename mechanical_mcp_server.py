@_tool
def connect_to_mechanical(port: int) -> str:
    """Connect to a running ANSYS Mechanical session on this machine (one at a time).
    Connecting again replaces the connection only if the new session answers. The handshake
    is bounded (MECHANICAL_MCP_CONNECT_TIMEOUT_S, default 20 s): a port that is not Mechanical
    is reported, it does not freeze the server.
    Args: port: gRPC port reported by Workbench (changes every session)"""
    ms.integer("port", port, 1, 65535)
    if _background_running():
        return _busy()
    try:
        import ansys.mechanical.core  # noqa: F401
    except ImportError as e:
        return _json(
            {
                "ok": False,
                "error": "Could not import ansys-mechanical-core: %s" % e,
                "hint": (
                    "Install it with 'pip install ansys-mechanical-core'. If the package "
                    "is installed and the message above mentions a DLL load failure or an "
                    "Application Control policy, reinstalling will not help -- see the "
                    "Troubleshooting section of the README."
                ),
            }
        )
    try:
        info = _connect(port)
    except Exception as e:
        return _json({"ok": False, "error": str(e)})
    _RECONNECTED.clear()
    return _json(
        {
            "ok": True,
            "port": port,
            "project": info.get("project", ""),
            "analyses": info.get("analyses", []),
        }
    )


@_tool
def disconnect_from_mechanical(shutdown: bool = False, confirm: str = "") -> str:
    """Disconnect from Mechanical, leaving the session running.
    Args: shutdown (True sends Mechanical a forced exit request whoever started it, so unsaved
    work is lost; the result says whether the session's port actually closed), confirm (must be
    exactly "SHUT DOWN MECHANICAL" for shutdown to proceed)"""
    if _background_running():
        return _busy()
    if _mechanical is None:
        _forget_port()
        if shutdown:
            return _json({"ok": False, "error": "Not connected, so there is nothing to shut down."})
        return _json({"ok": True, "message": "Not connected."})
    if shutdown:
        if confirm != "SHUT DOWN MECHANICAL":
            return _json(
                {
                    "ok": False,
                    "error": "Refusing to shut Mechanical down: this closes the session for everyone "
                    "and unsaved work is lost. The phrase confirm='SHUT DOWN MECHANICAL' is only a guard "
                    "against accidents, not an authorisation: only use it if the person you work for asked "
                    "for exactly this. Disconnecting without shutdown is the normal way to finish.",
                }
            )
        port = _port
        with _Locked(PROBE_WAIT_S) as lock:
            if not lock.ok:
                return _busy()
            failed = None
            try:
                _mechanical.exit(force=True)
            except Exception as e:
                failed = str(e)
            if failed is not None:
                return _json({"ok": False, "error": "Shutdown failed: " + failed})
            _close_channel()
        _forget_port()
        deadline = time.time() + SHUTDOWN_WAIT_S
        while port and _port_open(port) and time.time() < deadline:
            time.sleep(0.25)
        gone = not (port and _port_open(port))
        return _json(
            {
                "ok": True,
                "process_exited": gone,
                "message": "Mechanical session shut down."
                if gone
                else "Shutdown was requested but the session's port is still open after %g s."
                % SHUTDOWN_WAIT_S,
            }
        )
    with _Locked(PROBE_WAIT_S) as lock:
        if not lock.ok:
            return _busy()
        _close_channel()
    _forget_port()
    return _json({"ok": True, "message": "Disconnected. Mechanical is still running."})


@_tool
def check_mechanical_connection() -> str:
    """Check connection status. While another call (for example a blocking solve) is using
    Mechanical this answers at once with connected: true, busy: true instead of waiting."""
    if _mechanical is None and not _last_port():
        return _json({"ok": True, "connected": False})
    if _background_running():
        return _json(
            {"ok": True, "connected": True, "busy": True, "note": "a background solve is running"}
        )
    if _mechanical is None and _check_connection():
        return _json({"ok": True, "connected": False})
    with _Locked(PROBE_WAIT_S) as lock:
        if not lock.ok:
            return _json(
                {
                    "ok": True,
                    "connected": _mechanical is not None,
                    "busy": True,
                    "port": _port,
                    "note": "Mechanical is busy with another call (probably a solve)",
                }
            )
        raw = _run(_INFO_SCRIPT)
    data = _extract_json(raw)
    if _script_error(raw) is not None or data is None:
        return _json({"ok": True, "connected": False})
    return _with_reconnect_note(
        _json(
            {
                "ok": True,
                "connected": True,
                "busy": False,
                "port": _port,
                "project": data.get("project", ""),
                "analyses": data.get("analyses", []),
            }
        )
    )


