@_tool
def add_contact(
    contact_type: str,
    source_entity_ids: str = "",
    source_box_mm: str = "",
    source_body: str = "",
    target_entity_ids: str = "",
    target_box_mm: str = "",
    target_body: str = "",
    entity_type: str = "face",
    friction_coefficient: float = 0.0,
    reuse_existing: bool = True,
    update_existing: bool = False,
) -> str:
    """Add a contact region between two sets of geometry. Each side is given by entity ids or a
    bounding box in mm ("xmin,xmax,ymin,ymax,zmin,zmax", blank = open; entities are chosen by
    CENTROID) plus an optional body name. Nothing is created on error. A region that already joins
    exactly these entities is returned if its type (and friction) match (already_exists: true,
    with its suppressed state); if they differ the call is refused with the differences unless
    update_existing=true, which changes type/friction and reports `updated`. Args: contact_type (bonded, no_separation,
    frictionless, rough, frictional), source_*, target_*, entity_type (face/edge),
    friction_coefficient, reuse_existing, update_existing"""
    ms._check_contact(contact_type, friction_coefficient)
    src = ms.location_snippet("", source_entity_ids, source_box_mm, entity_type, source_body)
    tgt = ms.location_snippet("", target_entity_ids, target_box_mm, entity_type, target_body)
    return _scripted(
        ms.add_contact_script,
        src,
        tgt,
        contact_type,
        friction_coefficient,
        reuse_existing,
        update_existing,
    )


def _cleanup_stale_temp(max_age_s: float = 86400.0) -> int:
    """Delete script/output temp files left by a run that was killed (older than a day)."""
    n = 0
    try:
        now = time.time()
        for pattern in ("mech_script_*.py", "mech_out_*.txt"):
            for f in Path(tempfile.gettempdir()).glob(pattern):
                try:
                    if now - f.stat().st_mtime > max_age_s:
                        f.unlink()
                        n += 1
                except OSError:
                    pass
    except OSError:
        pass
    return n


def main():
    _cleanup_stale_temp()
    # stderr, never stdout: MCP frames JSON-RPC on stdout, so a banner
    # written there is protocol corruption that strict clients reject.
    print("ANSYS Mechanical MCP Server v" + __version__, file=sys.stderr)
    print("Starting...", file=sys.stderr)
    mcp.run()


if __name__ == "__main__":
    main()
