def _temp_paths():
    """Unique script/output paths for a single call (not next to the module: a non-editable
    install puts that in a read-only site-packages, and two clients sharing a path would
    overwrite each other's script)."""
    handle, script = tempfile.mkstemp(prefix="mech_script_", suffix=".py")
    os.close(handle)
    handle, out = tempfile.mkstemp(prefix="mech_out_", suffix=".txt")
    os.close(handle)
    return Path(script).as_posix(), Path(out).as_posix()


# IronPython's str() and json.dumps() raise on any non-ASCII text ('unknown' codec error), so a
# model object with a degree sign or an accent broke every tool that formatted its name (seen
# live). For the scripts this server generates, str falls back to unicode and json.dumps
# defaults to ensure_ascii=False for the duration of the run; both are restored afterwards.
# Scripts passed to run_mechanical_script keep stock IronPython behaviour.
_SAFE_TEXT_ON = (
    "def _safestr(x=''):\n"
    "    try:\n"
    "        return _str_orig(x)\n"
    "    except UnicodeError:\n"
    "        try:\n"
    "            return unicode(x)\n"
    "        except Exception:\n"
    "            return u'?'\n"
    "def _jm_dumps(o, *a, **k):\n"
    "    k.setdefault('ensure_ascii', False)\n"
    "    return _jm_orig(o, *a, **k)\n"
    "_jm.dumps=_jm_dumps\n"
    "globals()['str']=_safestr\n"
)


def _wrapper(script_file: str, out_file: str, safe_text: bool) -> str:
    """The code sent to Mechanical: run the script file, capture print() into the output file.

    A generated script runs in a private copy of the globals, so names it defines can neither
    depend on nor leak into another tool's script. A caller's own script (safe_text=False)
    shares the persistent globals, as before.
    """
    run_in = "dict(globals())" if safe_text else "globals()"
    return (
        "import sys as _sys\n"
        "class _Cap:\n"
        "    def __init__(self): self.d=[]\n"
        "    def write(self,s): self.d.append(s)\n"
        "    def flush(self): pass\n"
        "_cap=_Cap()\n"
        "_orig=_sys.stdout\n"
        "_sys.stdout=_cap\n"
        "import json as _jm\n"
        "import __builtin__ as _bi\n"
        "_jm_orig=_jm.dumps\n"
        "_str_orig=_bi.str\n" + (_SAFE_TEXT_ON if safe_text else "") + "try:\n"
        "    import io as _io\n"
        "    with _io.open("
        + ms.lit(script_file)
        + ", encoding='utf-8') as _sf: _code=_sf.read()\n"
        "    _scope=" + run_in + "\n"
        "    exec(_code, _scope)\n"
        "except Exception as _e:\n"
        "    _cap.d.append('Script error: ' + str(_e) + '\\n')\n"
        "finally:\n"
        "    _sys.stdout=_orig\n"
        "    _jm.dumps=_jm_orig\n"
        "    _scope=None\n"
        "    if 'str' in globals():\n"
        "        del globals()['str']\n"
        # captured text may be IronPython str or unicode; normalise to unicode by code point
        # before writing UTF-8 (verified live: the round trip is lossless)
        "    def _cl(x):\n"
        "        out = []\n"
        "        i = 0\n"
        "        n = len(x)\n"
        "        while i < n:\n"
        "            c = ord(x[i])\n"
        "            if 0xD800 <= c <= 0xDBFF and i + 1 < n and 0xDC00 <= ord(x[i + 1]) <= 0xDFFF:\n"
        "                out.append(x[i])\n"
        "                out.append(x[i + 1])\n"
        "                i += 2\n"
        "                continue\n"
        "            if 0xD800 <= c <= 0xDFFF:\n"
        "                out.append(u'\\\\u%04x' % c)\n"
        "            else:\n"
        "                out.append(x[i])\n"
        "            i += 1\n"
        "        return u''.join(out)\n"
        "    def _u(x):\n"
        "        if isinstance(x, unicode):\n"
        "            return _cl(x)\n"
        "        try:\n"
        "            return u''.join([unichr(ord(c)) for c in x])\n"
        "        except:\n"
        "            return u'?'\n"
        "    with _io.open(" + ms.lit(out_file) + ", 'w', encoding='utf-8') as _f:\n"
        "        _f.write(u''.join([_u(x) for x in _cap.d]))\n"
    )


class _RunFailed(Exception):
    """run_python_script itself raised (timeout, dropped channel); the script may have run."""


def _execute(mech, script: str, safe_text: bool = True) -> str:
    """Send script to the Mechanical session `mech` and return what it printed.

    Raises _RunFailed if the gRPC call fails. Never re-sends the script.
    """
    script_file, out_file = _temp_paths()
    try:
        with open(script_file, "w", encoding="utf-8") as fh:
            fh.write(script)
        try:
            mech.run_python_script(_wrapper(script_file, out_file, safe_text))
        except Exception as e:
            raise _RunFailed(str(e)) from e
        try:
            with open(out_file, "r", encoding="utf-8") as fh:
                result = fh.read().strip()
        except Exception:
            result = ""
        return result if result else "(done)"
    finally:
        for path in (out_file, script_file):
            try:
                os.remove(path)
            except Exception:
                pass


_TEXT_ERRORS = (
    "EncoderFallback",
    "Unable to translate Unicode",
    "UnicodeEncodeError",
    "UnicodeDecodeError",
)


def _is_text_error(text) -> bool:
    """A .NET/IronPython text-encoding failure (a name Mechanical cannot encode): a problem with
    the request, not a dead channel -- dropping the connection for it only hides the cause."""
    t = str(text)
    return any(k in t for k in _TEXT_ERRORS)


def _summarise_error(text) -> str:
    """One clear line from a transport error (gRPC dumps run to dozens of lines)."""
    t = str(text)
    code = re.search(r"StatusCode\.(\w+)", t)
    if code:
        det = re.search(r'details = "([^"]*)"', t)
        return "gRPC %s%s" % (code.group(1), (": " + det.group(1)[:160]) if det else "")
    lines = [ln for ln in t.splitlines() if ln.strip()]
    return (lines[0].strip()[:200]) if lines else "unknown error"


def _run(script, safe_text=True):
    """Run script in Mechanical, capturing print() output via temp files.

    A script is never re-sent after a failure: a timeout or dropped connection does not tell us
    whether Mechanical already ran it, and re-running Solve or an Add* call would duplicate work.
    The channel is dropped instead and the next call reconnects to the remembered port.
    """
    if not _acquire_mech(LOCK_WAIT_S):
        return (
            "Error: Mechanical is busy with another call (for example a solve). Try again shortly."
        )
    try:
        if _mechanical is None:
            return "Error: not connected to Mechanical"
        failed = None
        try:
            return _execute(_mechanical, script, safe_text)
        except _RunFailed as e:
            failed = str(e)
        except Exception as e:
            return "Error: " + str(e)
        if _is_text_error(failed):
            return (
                "Error: Mechanical could not encode a name or text in the request (%s); the request "
                "was rejected and the connection was kept" % _summarise_error(failed)
            )
        # Outside the except block on purpose: while it is active the traceback keeps the failed
        # call's frames (and so the connection object) alive, the finalizer could not run before
        # the channel is closed, and that crashed the whole process (see _drop).
        _close_channel()
        return (
            "Error: %s (connection dropped; the script may or may not have run, so check the "
            "model before retrying)\n[detail] %s" % (_summarise_error(failed), failed[:1500])
        )
    finally:
        _MECH_LOCK.release()


