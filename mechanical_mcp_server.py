@_tool
def linearize_path(
    nodal_file: str,
    start_mm: str,
    end_mm: str,
    plane: str = "xy",
    samples: int = 81,
    slice_mm: float | None = None,
    slice_tol_mm: float = 0.01,
    allow_unsigned: bool = False,
    allow_gaps: bool = False,
    expect_component: str = "",
    snap_fraction: float = 0.25,
    accept_direction_mismatch: bool = False,
) -> str:
    """Membrane + bending + peak linearization (ASME definition: peak = total - membrane -
    bending) of an exported SIGNED stress component along a straight section line. Refuses
    unsigned quantities (von Mises, stress intensity) unless allow_unsigned - linearizing an
    absolute value is non-conservative. Needs numpy and scipy (pip install
    ansys-mechanical-mcp[postproc]).
    Args: nodal_file (.json from export_nodal_results, inside MECHANICAL_MCP_ROOTS), start_mm and
    end_mm as "x,y,z" (3D line) or "a,b" in `plane` (xy, xz, yz; then the data must lie in one
    plane or slice_mm must give the coordinate normal to the plane), samples (2-5000),
    slice_mm/slice_tol_mm, allow_unsigned, allow_gaps (a line that crosses a hole or notch is an
    error because the value would be interpolated across the void; true accepts it and reports
    interpolated_across_gap), expect_component (x/y/z: error if the export holds another one).
    snap_fraction (0-1: a line end that falls outside the mesh by less than this fraction of an
    element, e.g. on a curved boundary, is extrapolated and reported in endpoint_adjustments; farther
    out is an error), accept_direction_mismatch (a line that runs along a different axis than the
    exported component is refused unless true). A gap is detected against the LOCAL element size
    (median distance of the nearest node to its 6 nearest distinct nodes), after merging
    coincident nodes; the error carries gap_diagnostics. value_unit is "unverified" unless the
    export cross-checked it against the result's maximum.
    Only the single exported scalar is linearized; nothing is combined from other components.
    Large exports are limited by MECHANICAL_MCP_MAX_NODES and the run by
    MECHANICAL_MCP_LINEARIZE_TIMEOUT_S."""
    ms.integer("samples", samples, 2, 5000)
    if plane not in ("xy", "xz", "yz"):
        raise ValueError("plane must be xy, xz or yz")
    sl = None if slice_mm is None else ms.num("slice_mm", slice_mm, limit=1e9)
    tol = ms.num("slice_tol_mm", slice_tol_mm, positive=True, limit=1e6)
    a = _point("start_mm", start_mm)
    b = _point("end_mm", end_mm)
    if len(a) != len(b):
        raise ValueError("start_mm and end_mm need the same number of coordinates (2 or 3)")
    p, err = _allow(nodal_file, exts={".json"})
    if err:
        return err
    try:
        import mechanical_postproc as pp

        cancel = threading.Event()
        out = _call_with_timeout(
            lambda: pp.linearize_file(
                str(p),
                a,
                b,
                plane,
                samples,
                slice_mm=sl,
                slice_tol_mm=tol,
                allow_unsigned=bool(allow_unsigned),
                allow_gaps=bool(allow_gaps),
                expect_component=expect_component,
                snap_fraction=snap_fraction,
                accept_direction_mismatch=bool(accept_direction_mismatch),
                cancel=cancel,
            ),
            LINEARIZE_TIMEOUT_S,
            limiter=_LIN_SLOT,
            limiter_message="another linearization is still running (a timed-out one is told to stop and "
            "ends shortly); try again in a moment",
            on_timeout=cancel.set,
        )
        return _json({"ok": True, **out})
    except BusyError as e:
        return _json({"ok": False, "busy": True, "error": str(e)})
    except TimeoutError:
        return _json(
            {
                "ok": False,
                "error": "linearization did not finish within %g s (MECHANICAL_MCP_LINEARIZE_TIMEOUT_S); "
                "use a smaller export" % LINEARIZE_TIMEOUT_S,
            }
        )
    except ModuleNotFoundError as e:
        return _json(
            {
                "ok": False,
                "error": "%s - install with: pip install ansys-mechanical-mcp[postproc]" % e,
            }
        )
    except ValueError as e:
        out = {"ok": False, "error": str(e)}
        if getattr(e, "diagnostics", None):
            out["gap_diagnostics"] = e.diagnostics
        return _json(out)
    except Exception as e:  # every other numerical or file failure still becomes a clear message
        return _json({"ok": False, "error": "%s: %s" % (type(e).__name__, e)})


def _point(name: str, text: str):
    ms.check_text(name, text)
    parts = [p.strip() for p in text.split(",")]
    if len(parts) not in (2, 3):
        raise ValueError("%s needs 2 or 3 comma-separated numbers" % name)
    out = []
    for p in parts:
        if not ms._ASCII_NUMBER.fullmatch(p):
            raise ValueError("%s: %r is not a number" % (name, p))
        out.append(ms.num(name, float(p), limit=1e9))
    return tuple(out)


